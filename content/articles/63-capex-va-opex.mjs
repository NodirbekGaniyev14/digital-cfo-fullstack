<p>Shuning uchun har CAPEX qarorini <a href="/blog/npv-va-irr">NPV</a> bilan baholang: aktiv keltiradigan kelajakdagi pul oqimini bugungi qiymatga keltirib, investitsiyadan ayiring. NPV musbat bo'lsa — arziydi. Bu CAPEX'ni "xarid" emas, "investitsiya" sifatida ko'rish demakdir — chunki u aynan shunday.</p>

