<p>Bu farq muhim, chunki noto'g'ri tasniflash foydani buzadi. Katta OPEX'ni CAPEX deb yozish foydani sun'iy oshiradi (xarajat yillarga tarqaladi); katta CAPEX'ni OPEX deb yozish esa foydani sun'iy kamaytiradi. Izchil va to'g'ri tasniflash — hisobot ishonchliligining asosi. Shubha bo'lsa, buxgalter yoki soliq maslahatchisi bilan tekshiring, chunki soliq qonunchiligida ham bu farq belgilangan.</p>

