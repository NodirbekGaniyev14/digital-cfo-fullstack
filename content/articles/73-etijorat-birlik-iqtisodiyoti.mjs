<p>Shuning uchun to'g'ri savol — "bitta buyurtma foydalimi" emas, "bitta mijoz o'z umri davomida foydalimi" (LTV). Agar mijoz o'rtacha uch marta xarid qilsa, CAC uch buyurtmaga taqsimlanadi va birlik iqtisodiyoti butunlay o'zgaradi. Aynan shuning uchun onlayn biznesda takroriy xaridni oshirish — sodiqlik, sifat, mijozga g'amxo'rlik — CAC'ni kamaytirishdan ko'ra ko'pincha muhimroq. Bir marta jalb qilingan mijozning qaytishi eng arzon "yangi sotuv".</p>

